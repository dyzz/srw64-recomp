#!/usr/bin/env python3
"""Write the host's portrait identity table from content/art/portrait-identities.json.

    python3 tools/content/portrait_identities.py                 # writes src/host/portrait_identities_table.hpp
    python3 tools/content/portrait_identities.py --check         # exits 1 when the header is out of date
    python3 tools/content/portrait_identities.py --from MANIFEST # first refreshes the JSON from an HD pack's
                                                                 # srw64-portraits-hd.json

The host recognises a portrait by FNV-1a 64 digests of the index and palette data its draw
points at (native_portrait.cpp). The HD pack's manifest carries them; MOD portraits
(art/portraits/<pilot>.png) need them without the HD pack, so the digests, which are
derived from the ROM's data and hold none of it, live in the base game too.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content/art/portrait-identities.json"
HEADER = ROOT / "src/host/portrait_identities_table.hpp"


def refresh(manifest: Path) -> None:
    spec = json.loads(manifest.read_text(encoding="utf-8"))
    if spec.get("schema") != "srw64.portrait-images.v1":
        sys.exit(f"{manifest}: not srw64.portrait-images.v1")
    rows = [{"image": r["image"], "palette": r["palette"], "pixels_fnv1a64": r["pixels_fnv1a64"],
             "palette_fnv1a64": r["palette_fnv1a64"]} for r in spec["images"]]
    rows.sort(key=lambda r: (r["image"], r["palette"]))
    data = {"schema": "srw64.portrait-identities.v1",
            "note": "Digests of the original portraits' index and palette data, from the HD pack's srw64-portraits-hd.json; "
                    "regenerate with tools/content/portrait_identities.py --from.",
            "silhouette": {"palette_fnv1a64": spec["silhouette"]["palette_fnv1a64"], "rgb": spec["silhouette"]["rgb"]},
            "images": rows}
    SOURCE.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(SOURCE.relative_to(ROOT))


def header() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = "\n".join(f"    {{{r['image']}, {r['palette']}, 0x{r['pixels_fnv1a64']}ull, 0x{r['palette_fnv1a64']}ull}},"
                     for r in data["images"])
    rgb = ", ".join(str(c) for c in data["silhouette"]["rgb"])
    return ("#pragma once\n"
            "// Generated by tools/content/portrait_identities.py from content/art/portrait-identities.json; do not edit.\n"
            "// Each original portrait (image, palette) and the FNV-1a 64 digests of its index and palette data.\n"
            "#include <cstdint>\n"
            "namespace srw64::portraits {\n"
            "struct Identity { uint16_t image, palette; uint64_t pixels, palette_digest; };\n"
            "constexpr Identity kIdentities[] = {\n"
            f"{rows}\n"
            "};\n"
            f"constexpr uint64_t kSilhouettePalette = 0x{data['silhouette']['palette_fnv1a64']}ull;\n"
            f"constexpr uint8_t kSilhouetteRgb[3] = {{{rgb}}};\n"
            "}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--from", dest="manifest", type=Path)
    args = parser.parse_args()
    if args.manifest:
        refresh(args.manifest)
    text = header()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    print(HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
