#!/usr/bin/env python3
"""Write the host's Library name table from content/locales/library-names.json.

    python3 tools/content/library_names.py          # writes src/host/library_names_table.hpp
    python3 tools/content/library_names.py --check  # exits 1 when the header is out of date

A row names one Library record in one language, in place of the game's "(2)" numbering;
src/host/library.cpp and web/scripts/export_library.py apply it after numbering.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content/locales/library-names.json"
HEADER = ROOT / "src/host/library_names_table.hpp"


def header() -> str:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    rows = []
    for kind, pilot in (("units", "false"), ("pilots", "true")):
        for rid, names in sorted(data[kind].items(), key=lambda x: int(x[0])):
            for locale, name in sorted(names.items()):
                rows.append(f'    {{{pilot},{int(rid)},"{locale}",{json.dumps(name, ensure_ascii=False)}}},')
    return ("#pragma once\n"
            "// Generated by tools/content/library_names.py from content/locales/library-names.json; do not edit.\n"
            "// One Library record's name in one language, in place of the game's numbering.\n"
            "namespace srw64::library_names {\n"
            "struct Name{bool pilot;unsigned id;const char* locale;const char* name;};\n"
            "constexpr Name kNames[] = {\n"
            + "\n".join(rows) + "\n"
            "};\n"
            "}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = header()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    print(HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
