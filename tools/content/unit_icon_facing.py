#!/usr/bin/env python3
"""Write the host's map unit icon facing table from content/art/unit-icon-facing.json.

    python3 tools/content/unit_icon_facing.py          # writes src/host/unit_icon_facing_table.hpp
    python3 tools/content/unit_icon_facing.py --check  # exits 1 when the header is out of date

The table is one character per icon resource 688-1009: L (looks left), R (looks right),
F (front, never mirrored); resources without an icon are F. See docs/native/unit-icon-facing.md.
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content/art/unit-icon-facing.json"
HEADER = ROOT / "src/host/unit_icon_facing_table.hpp"
FIRST, LAST = 688, 1009
CODES = {"left": "L", "right": "R", "front": "F"}


def header() -> str:
    icons = json.loads(SOURCE.read_text(encoding="utf-8"))["icons"]
    codes = "".join(CODES[icons[str(rid)]["facing"]] if str(rid) in icons else "F" for rid in range(FIRST, LAST + 1))
    rows = "\n".join(f'    "{codes[i:i + 64]}"' for i in range(0, len(codes), 64))
    return ("#pragma once\n"
            "// Generated by tools/content/unit_icon_facing.py from content/art/unit-icon-facing.json; do not edit.\n"
            "// One character per map icon resource from 688: L looks left, R looks right, F front.\n"
            "namespace srw64::unit_icon_facing {\n"
            f"constexpr unsigned kFirstIcon = {FIRST}, kLastIcon = {LAST};\n"
            "constexpr char kFacing[] =\n"
            f"{rows};\n"
            "}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = header()
    if args.check:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run {Path(__file__).relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text)
    print(HEADER.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
