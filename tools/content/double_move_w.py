#!/usr/bin/env python3
"""Write the host's embedded 二回行動 W picture from content/art/double-move-w.png.

    python3 tools/content/double_move_w.py          # writes src/host/double_move_w.hpp
    python3 tools/content/double_move_w.py --check  # exits 1 when the header is out of date

The PNG is the user's drawing of the original's crown glyph (2026-10-30), trimmed and
fitted into a 14 x 12 cell (224 x 192 pixels, 16 per original pixel) with its alpha
premultiplied before resampling. The native pilot page draws it beside the level in the
HD images mode (docs/native/native-ability-screens.md); embedding it needs no new bundled
folder on any platform.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "content/art/double-move-w.png"
HEADER = ROOT / "src/host/double_move_w.hpp"


def header() -> str:
    data = SOURCE.read_bytes()
    rows = "\n".join("    " + ",".join(f"0x{b:02x}" for b in data[i:i + 24]) + "," for i in range(0, len(data), 24))
    return (f"// Generated by tools/content/double_move_w.py from content/art/double-move-w.png; do not edit.\n"
            f"#pragma once\n#include <cstddef>\n\nnamespace srw64::double_move_w {{\n"
            f"// A 224 x 192 PNG: the 二回行動 W in a 14 x 12 cell.\n"
            f"inline constexpr unsigned char png[{len(data)}]={{\n{rows}\n}};\n"
            f"inline constexpr std::size_t size={len(data)};\n}}\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = header()
    if args.check:
        if not HEADER.exists() or HEADER.read_text(encoding="utf-8") != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run tools/content/double_move_w.py", file=sys.stderr)
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(HEADER.relative_to(ROOT), len(text), "bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
