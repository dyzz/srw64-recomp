#!/usr/bin/env python3
"""The PS Vita V0 feasibility probe (docs/design/psv-port.md): compile the recompiled game
for 32-bit ARM and measure it; run it under qemu-arm and compare its memory with a native run.

Inside the container tools/release/vita/build.sh starts (VitaSDK + arm-linux-gnueabihf +
qemu-arm), or natively on macOS/Linux for the reference run:

  --prepare-only   run prepare_runtime_lifecycle.py and prepare_vita_runtime.py, nothing else
                   (build.sh does this on the host, where git owns the checkouts)
  --vita           srw64_cpu, srw64_audio, librecomp and ultramodern with arm-vita-eabi-gcc,
                   once at -O2 and once at -Os: .text sizes, build times and the pointer-width
                   warnings into the report (the default when nothing else is asked)
  --qemu           the headless probe host (probe_host.cpp) with arm-linux-gnueabihf-g++,
                   run under qemu-arm for FRAMES game frames; its RDRAM snapshot is compared
                   with --native's when both exist
  --native         the probe host with this machine's compiler and a run on it
  --warnings       the runtime (librecomp, ultramodern, srw64_audio) once more with the Linux
                   ARMv7 compiler at -Wall -Wextra, for the full list of pointer-width warnings
                   (the runtime builds without -Wall)
  --frames N       game frames to run before the snapshot (300)
  --jobs N         parallel compile jobs (the machine's CPUs)
  --rom PATH       the ROM (rom.z64)

Everything lands in build/recomp/vita/: vita-O2/, vita-Os/, gnueabihf/, native/, the runs
and report.json, which docs/design/psv-port.md quotes.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent
WORK = ROOT / "build/recomp/vita"
LIBRARIES = ("srw64_cpu", "srw64_audio", "librecomp", "ultramodern")
# The three pointer-width conversions the plan lists; the report checks each was seen.
KNOWN_POINTER_WIDTH = ("misc_ultra.cpp:12", "ultra64.h:43", "ultra64.h:106", "native_marker.cpp:318")


def run(argv: list, cwd: Path | None = None, log: Path | None = None, env: dict | None = None) -> float:
    print("+ " + " ".join(str(a) for a in argv), flush=True)
    started = time.monotonic()
    if log is None:
        subprocess.run([str(a) for a in argv], cwd=cwd, env=env, check=True)
    else:
        with log.open("a") as handle:
            subprocess.run([str(a) for a in argv], cwd=cwd, env=env, check=True, stdout=handle, stderr=subprocess.STDOUT)
    return time.monotonic() - started


def prepare() -> None:
    python = sys.executable
    run([python, ROOT / "tools/recomp/toolchain/prepare_runtime_lifecycle.py"])
    run([python, ROOT / "tools/recomp/toolchain/prepare_vita_runtime.py"])


def hook_trampolines() -> str:
    """probe_hooks.cpp: every native hook of the game host calls its original, except the
    frame boundary, which probe_host.cpp defines."""
    text = (ROOT / "tools/recomp/toolchain/generate_cpu.py").read_text()
    body = text[text.index("NATIVE_HOOKS = {"):]
    body = body[:body.index("\n}\n")]
    hooks = re.findall(r'"([A-Za-z0-9_]+)":\s*"(srw64_original_[a-z0-9_]+)"', body)
    if len(hooks) < 100:
        raise RuntimeError("NATIVE_HOOKS not found in generate_cpu.py")
    lines = ["// Generated by tools/release/vita/build_probe.py from generate_cpu.py NATIVE_HOOKS.",
             '#include "funcs.h"', ""]
    # Two more the generator renames outside the table (its rom_read/text_descriptor step).
    hooks += [("resident_func_8007F704", "srw64_original_rom_read"), ("resident_func_8008C510", "srw64_original_text_descriptor")]
    for hooked, original in hooks:
        if hooked in ("resident_func_80085F30", "resident_func_8007F704"):
            continue
        lines.append(f"extern \"C\" void {hooked}(uint8_t* rdram, recomp_context* ctx) {{ {original}(rdram, ctx); }}")
    return "\n".join(lines) + "\n"


def lockstep_events() -> str:
    """probe_events.cpp: ultramodern's events.cpp with the VI thread paced by the game instead of
    the clock (one VI per frame boundary the probe sees, srw64_probe_wait_vi in probe_host.cpp),
    so two builds of the probe see the same VIs, audio tasks and display lists at the snapshot."""
    source = (ROOT / "build/recomp/upstream/N64ModernRuntime/ultramodern/src/events.cpp").read_text()
    old = """        ultramodern::sleep_until(next);
        auto time_now = ultramodern::time_since_start();
        // Calculate how many VIs have passed
        uint64_t new_total_vis = (time_now * (60 * ultramodern::get_speed_multiplier()) / 1000ms) + 1;
        if (new_total_vis > total_vis + 1) {
            //printf("Skipped % " PRId64 " frames in VI interupt thread!\\n", new_total_vis - total_vis - 1);
        }
        total_vis = new_total_vis;
"""
    new = """        // The V0 probe (tools/release/vita/probe_host.cpp): the next VI once the game has
        // passed a frame boundary, or after a wait where it is not frame-paced (boot, loads).
        (void)next;
        srw64_probe_wait_vi();
        total_vis += 1;
"""
    if source.count(old) != 1:
        raise RuntimeError("ultramodern events.cpp differs from the pinned text the probe patches")
    return "void srw64_probe_wait_vi();\n" + source.replace(old, new)


def text_sizes(build: Path, size_tool: str) -> dict:
    """Per library: the sum of its members' .text (and .text.*) and the archive's size."""
    sizes = {}
    for library in LIBRARIES:
        archive = next(build.rglob(f"lib{library}.a"))
        output = subprocess.run([size_tool, "-A", str(archive)], check=True, capture_output=True, text=True).stdout
        text = rodata = data = bss = 0
        for line in output.splitlines():
            parts = line.split()
            if len(parts) < 2 or not parts[1].isdigit():
                continue
            name, value = parts[0], int(parts[1])
            if name == ".text" or name.startswith(".text."):
                text += value
            elif name == ".rodata" or name.startswith(".rodata."):
                rodata += value
            elif name == ".data" or name.startswith(".data."):
                data += value
            elif name == ".bss" or name.startswith(".bss."):
                bss += value
        sizes[library] = {"text": text, "rodata": rodata, "data": data, "bss": bss, "archive": archive.stat().st_size}
    sizes["total"] = {key: sum(sizes[library][key] for library in LIBRARIES) for key in ("text", "rodata", "data", "bss", "archive")}
    return sizes


def warnings_in(log: Path) -> dict:
    """The compiler's warnings, by kind, and the ones about pointer width."""
    pattern = re.compile(r"^(?P<file>[^:\s]+):(?P<line>\d+):(?:\d+:)? warning: (?P<text>.*?)(?: \[-W(?P<flag>[^\]]+)\])?$")
    by_flag: dict[str, int] = {}
    pointer_width = []
    seen = set()
    for raw in log.read_text(errors="replace").splitlines():
        match = pattern.match(raw.strip())
        if not match:
            continue
        key = (match["file"], match["line"], match["text"])
        if key in seen:
            continue
        seen.add(key)
        flag = match["flag"] or "other"
        by_flag[flag] = by_flag.get(flag, 0) + 1
        text = match["text"]
        if (flag in ("int-to-pointer-cast", "pointer-to-int-cast", "overflow", "shift-count-overflow", "narrowing")
                or "pointer" in text and ("cast" in text or "different size" in text)
                or "changes value" in text):
            pointer_width.append({"file": match["file"].replace(str(ROOT) + "/", ""), "line": int(match["line"]),
                                  "flag": flag, "text": text})
    pointer_width.sort(key=lambda w: (w["file"], w["line"]))
    known = {name: any(w["file"].endswith(name.split(":")[0]) and w["line"] == int(name.split(":")[1]) for w in pointer_width)
             for name in KNOWN_POINTER_WIDTH}
    return {"by_flag": dict(sorted(by_flag.items())), "pointer_width": pointer_width, "known_pointer_width_seen": known}


def errors_in(log: Path) -> list:
    pattern = re.compile(r"^(?P<file>[^:\s]+):(?P<line>\d+):(?:\d+:)? (?:fatal )?error: (?P<text>.*)$")
    found = []
    for raw in log.read_text(errors="replace").splitlines():
        match = pattern.match(raw.strip())
        if match:
            found.append({"file": match["file"].replace(str(ROOT) + "/", ""), "line": int(match["line"]), "text": match["text"]})
    return found


def build_vita(optimization: str, jobs: int) -> dict:
    vitasdk = os.environ.get("VITASDK", "/usr/local/vitasdk")
    build = WORK / f"vita-{optimization.lstrip('-')}"
    if build.exists():
        shutil.rmtree(build)
    build.mkdir(parents=True)
    log = build / "build.log"
    flags = f"{optimization} -DNDEBUG"
    configure = run(["cmake", "-S", HERE, "-B", build, "-G", "Ninja",
                     f"-DCMAKE_TOOLCHAIN_FILE={vitasdk}/share/vita.toolchain.cmake",
                     "-DCMAKE_BUILD_TYPE=None", f"-DCMAKE_C_FLAGS={flags}", f"-DCMAKE_CXX_FLAGS={flags}"], log=log)
    result = {"optimization": optimization, "flags": flags, "configure_seconds": round(configure, 1), "log": str(log.relative_to(ROOT))}
    try:
        result["build_seconds"] = round(run(["cmake", "--build", build, "--target", *LIBRARIES, "-j", str(jobs)], log=log), 1)
        result["status"] = "built"
    except subprocess.CalledProcessError:
        result["status"] = "failed"
        # The rest, for the full list of errors in one go.
        try:
            run(["cmake", "--build", build, "--target", *LIBRARIES, "-j", str(jobs), "--", "-k", "0"], log=log)
        except subprocess.CalledProcessError:
            pass
    result["errors"] = errors_in(log)
    result["warnings"] = warnings_in(log)
    if result["status"] == "built":
        result["sizes"] = text_sizes(build, f"{vitasdk}/bin/arm-vita-eabi-size")
        compiler = subprocess.run([f"{vitasdk}/bin/arm-vita-eabi-gcc", "--version"], check=True, capture_output=True, text=True).stdout
        result["compiler"] = compiler.splitlines()[0]
    return result


def build_host(name: str, toolchain: Path | None, jobs: int) -> dict:
    build = WORK / name
    if build.exists():
        shutil.rmtree(build)
    build.mkdir(parents=True)
    (build / "probe_hooks.cpp").write_text(hook_trampolines())
    (build / "probe_events.cpp").write_text(lockstep_events())
    log = build / "build.log"
    command = ["cmake", "-S", HERE, "-B", build, "-G", "Ninja", "-DSRW64_VITA_PROBE_HOST=ON",
               "-DCMAKE_BUILD_TYPE=None", "-DCMAKE_C_FLAGS=-O2 -DNDEBUG", "-DCMAKE_CXX_FLAGS=-O2 -DNDEBUG"]
    if toolchain:
        command.append(f"-DCMAKE_TOOLCHAIN_FILE={toolchain}")
    result = {"log": str(log.relative_to(ROOT))}
    try:
        run(command, log=log)
        result["build_seconds"] = round(run(["cmake", "--build", build, "--target", "srw64-vita-probe", "-j", str(jobs)], log=log), 1)
        result["status"] = "built"
        result["binary"] = str((build / "srw64-vita-probe").relative_to(ROOT))
    except subprocess.CalledProcessError:
        result["status"] = "failed"
    result["errors"] = errors_in(log)
    result["warnings"] = warnings_in(log)
    return result


def build_warnings(jobs: int) -> dict:
    build = WORK / "gnueabihf-wall"
    if build.exists():
        shutil.rmtree(build)
    build.mkdir(parents=True)
    log = build / "build.log"
    flags = "-O2 -DNDEBUG -Wall -Wextra -Wno-unused-parameter"
    result = {"flags": flags, "log": str(log.relative_to(ROOT))}
    try:
        run(["cmake", "-S", HERE, "-B", build, "-G", "Ninja", f"-DCMAKE_TOOLCHAIN_FILE={HERE / 'toolchain-gnueabihf.cmake'}",
             "-DCMAKE_BUILD_TYPE=None", f"-DCMAKE_C_FLAGS={flags}", f"-DCMAKE_CXX_FLAGS={flags}"], log=log)
        run(["cmake", "--build", build, "--target", "librecomp", "ultramodern", "srw64_audio", "-j", str(jobs), "--", "-k", "0"], log=log)
        result["status"] = "built"
    except subprocess.CalledProcessError:
        result["status"] = "failed"
    result["errors"] = errors_in(log)
    result["warnings"] = warnings_in(log)
    return result


def run_probe(name: str, binary: Path, rom: Path, frames: int, prefix: list) -> dict:
    output = WORK / f"{name}-run"
    if output.exists():
        shutil.rmtree(output)
    output.mkdir(parents=True)
    log = output / "console.log"
    command = [*prefix, binary, rom, output, str(frames), str(frames * 20)]
    print("+ " + " ".join(str(a) for a in command), flush=True)
    started = time.monotonic()
    with log.open("w") as handle:
        completed = subprocess.run([str(a) for a in command], stdout=handle, stderr=subprocess.STDOUT, timeout=4 * 3600)
    result = {"exit_code": completed.returncode, "seconds": round(time.monotonic() - started, 1),
              "log": str(log.relative_to(ROOT)), "snapshot": None}
    counters = output / "counters.json"
    if counters.is_file():
        result["counters"] = json.loads(counters.read_text())
    if (output / "rdram.bin").is_file():
        result["snapshot"] = str((output / "rdram.bin").relative_to(ROOT))
    return result


def compare(a: Path, b: Path) -> dict:
    """Byte ranges that differ between two RDRAM snapshots, as N64 addresses."""
    left, right = a.read_bytes(), b.read_bytes()
    if len(left) != len(right):
        return {"identical": False, "reason": "sizes differ", "sizes": [len(left), len(right)]}
    ranges = []
    start = None
    changed = 0
    for index in range(len(left)):
        if left[index] != right[index]:
            changed += 1
            if start is None:
                start = index
        elif start is not None:
            ranges.append((start, index))
            start = None
    if start is not None:
        ranges.append((start, len(left)))
    return {"identical": not ranges, "changed_bytes": changed, "ranges": len(ranges),
            "first_ranges": [{"start": f"{0x80000000 + s:08X}", "end": f"{0x80000000 + e:08X}", "bytes": e - s}
                             for s, e in ranges[:200]]}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--prepare-only", action="store_true")
    parser.add_argument("--vita", action="store_true")
    parser.add_argument("--qemu", action="store_true")
    parser.add_argument("--native", action="store_true")
    parser.add_argument("--warnings", action="store_true")
    parser.add_argument("--frames", type=int, default=300)
    parser.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    parser.add_argument("--rom", type=Path, default=ROOT / "rom.z64")
    args = parser.parse_args()
    if args.prepare_only:
        prepare()
        return 0
    if not (args.vita or args.qemu or args.native or args.warnings):
        args.vita = True
    WORK.mkdir(parents=True, exist_ok=True)
    report_path = WORK / "report.json"
    report = json.loads(report_path.read_text()) if report_path.is_file() else {"schema": "srw64.vita-probe.v1"}
    machine = {"platform": platform.platform(), "cpu_count": os.cpu_count(), "jobs": args.jobs}
    generated = sorted((ROOT / "build/recomp/cpu-bound/generated").glob("funcs_*.c"))
    report["generated"] = {"files": len(generated), "bytes": sum(path.stat().st_size for path in generated)}
    if args.vita:
        report["vita"] = {opt: build_vita(opt, args.jobs) for opt in ("-O2", "-Os")}
        report["vita"]["machine"] = machine
    if args.qemu:
        host = build_host("gnueabihf", HERE / "toolchain-gnueabihf.cmake", args.jobs)
        report["qemu"] = {"build": host}
        if host["status"] == "built":
            report["qemu"]["run"] = run_probe("qemu", ROOT / host["binary"], args.rom, args.frames, ["qemu-arm"])
        report["qemu"]["machine"] = machine
    if args.warnings:
        report["warnings_wall"] = build_warnings(args.jobs)
    if args.native:
        host = build_host("native", None, args.jobs)
        report["native"] = {"build": host}
        if host["status"] == "built":
            report["native"]["run"] = run_probe("native", ROOT / host["binary"], args.rom, args.frames, [])
        report["native"]["machine"] = machine
    snapshots = [ROOT / report[name]["run"]["snapshot"] for name in ("native", "qemu")
                 if name in report and report[name].get("run", {}).get("snapshot")]
    if len(snapshots) == 2:
        report["comparison"] = {"frames": args.frames, **compare(snapshots[0], snapshots[1])}
    report_path.write_text(json.dumps(report, indent=2) + "\n")
    print(f"report: {report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
