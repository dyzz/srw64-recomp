#!/usr/bin/env python3
"""The battle scenes the wide spread treats specially (src/host/battle_spread_scenes.inc).

Read from the ROM's scene data, all frames of a scene together, so a scene is one thing for
the whole of its animation:

- beams: drawn to one side of where they stand (a beam, a burst's trace, a wire, a chain),
  at least 96 across, and long (twice as wide as tall) or 160 across (a burst of shots drawn
  as one tall picture from the gun, 3570).
  The spread places both their ends.
- backdrops: reach 120 to both sides and are 170 tall, the special moves' pictures that
  covered the original's screen. The spread enlarges them whole.

Everything else a weapon's script shows only moves. Run with --write after the rule changes
and look at the difference; add a scene by hand to EXTRA_* below when one is found by eye.
"""
from __future__ import annotations
import argparse
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "src"))
from srw64_rom.resources import ResourceTable  # noqa: E402
from srw64_native.battle_graphics import parse_scene, read_triplets  # noqa: E402

OUTPUT = ROOT / "src/host/battle_spread_scenes.inc"
EXTRA_BEAMS: set[int] = {3591}   # the scatter bazooka's burst, 153 across
EXTRA_BACKDROPS: set[int] = set()
NOT_BEAMS: set[int] = set()
NOT_BACKDROPS: set[int] = set()


def extents(data: bytes):
    scene = parse_scene(data)
    if scene.vertex_mode > 1:
        return None
    xs, ys = [], []
    for frame, _ in scene.steps:
        if frame == 0xFF:
            continue
        for part in scene.frames[frame]:
            for v in range(4):
                x, y = struct.unpack_from(">2h", data, part.vertex_offset + v * 16)
                xs.append(x)
                ys.append(y)
    return (min(xs), max(xs), min(ys), max(ys)) if xs else None


def classify(rom: bytes):
    table = ResourceTable(rom)
    beams, backdrops = set(), set()
    for scene in sorted({s for s, _, _ in read_triplets(rom, "battle_scenes")}):
        try:
            box = extents(table.extract(scene)[0])
        except Exception:
            continue
        if not box:
            continue
        left, right, width, height = max(0, -box[0]), max(0, box[1]), box[1] - box[0], box[3] - box[2]
        if min(left, right) >= 120 and height >= 170:
            backdrops.add(scene)
        elif width >= 96 and min(left, right) <= 0.25 * max(left, right) and (width >= 2 * height or width >= 160):
            beams.add(scene)
    return (beams | EXTRA_BEAMS) - NOT_BEAMS, (backdrops | EXTRA_BACKDROPS) - NOT_BACKDROPS


def render(beams, backdrops) -> str:
    def rows(values):
        values = sorted(values)
        return "\n".join("    " + ", ".join(map(str, values[i:i + 16])) + "," for i in range(0, len(values), 16))
    return ("// Generated by tools/recomp/analysis/battle_spread_scenes.py from the ROM's scene data; sorted.\n"
            f"inline constexpr uint16_t kBeamScenes[] = {{\n{rows(beams)}\n}};\n"
            f"inline constexpr uint16_t kBackdropScenes[] = {{\n{rows(backdrops)}\n}};\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rom", type=Path, default=ROOT / "rom.z64")
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    beams, backdrops = classify(args.rom.read_bytes())
    text = render(beams, backdrops)
    print(f"beams {len(beams)}, backdrops {len(backdrops)}")
    if args.write:
        OUTPUT.write_text(text)
    elif not OUTPUT.exists() or OUTPUT.read_text() != text:
        raise SystemExit(f"{OUTPUT.relative_to(ROOT)} is out of date")


if __name__ == "__main__":
    main()
